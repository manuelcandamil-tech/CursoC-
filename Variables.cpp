#include <iostream>

int main() {
    int a = 5; // This is an integer variable
    double b = 3.14; // This is a double variable
    char c = 'A'; // This is a character variable
    bool d = true; // This is a boolean variable
    float e = 2.1458; // This is a float variable
    long double f = 3.1415926535897932384626433832795; // This is a long double variable
    std::string g= "Hello, World!"; // This is a string variable

    std::cout << "Integer: " << a << std::endl;
    std::cout << "Double: " << b << std::endl;
    std::cout << "Character: " << c << std::endl;
    std::cout << "Boolean: " << d << std::endl;
    std::cout << "Float: " << e << std::endl;
    std::cout << "Long Double: " << f << std::endl;
    std::cout << "String: " << g << std::endl;

    return 0;
}